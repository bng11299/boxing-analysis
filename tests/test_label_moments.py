def short_run(cmd, **k):
    done = real_run(cmd, **k)
    if "-frames:v" in cmd:
        size = len(done.stdout) // int(cmd[cmd.index("-frames:v") + 1])
        done.stdout = done.stdout[:size * 10]           # ffmpeg stopped after 10 frames
    return done


