PASS = FAIL = SKIP = 0


def check(name: str, cond: bool, detail: str = "") -> None:
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  ok   {name}")
    else:
        FAIL += 1
        print(f"  FAIL {name}" + (f"  ({detail})" if detail else ""))


def raises(name: str, fn, exc=lm.Refused, contains: str = "") -> None:
    try:
        fn()
    except exc as e:
        check(name, contains.lower() in str(e).lower(), f"message: {e}")
        return
    except Exception as e:     # noqa: BLE001
        check(name, False, f"raised {type(e).__name__}: {e}")
        return
    check(name, False, "did not raise")


def skip(name: str, why: str) -> None:
    global SKIP
    SKIP += 1
    print(f"  SKIP {name} ({why})")


# ---- synthetic material ---------------------------------------------------------------------------
W, H, FPS, BANDS = 320, 180, 30, 10


def frame_for(i: int) -> np.ndarray:
    f = np.zeros((H, W, 3), np.uint8)
    bw = W // BANDS
    for b in range(BANDS):
        if (i >> b) & 1:
            f[:, b * bw:(b + 1) * bw] = 255
    return f


def read_index(rgb: bytes, w: int, h: int) -> int:
    a = np.frombuffer(rgb, np.uint8).reshape(h, w, 3)
    bw = w / BANDS
    return sum(1 << b for b in range(BANDS) if a[h // 2, int((b + 0.5) * bw)].mean() > 128)


def make_video(path: Path, seconds: float, offset: int = 0, audio: bool = False) -> None:
    n = int(round(seconds * FPS))
    cmd = [shutil.which("ffmpeg"), "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24",
           "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-"]
    if audio:
        cmd += ["-f", "lavfi", "-i", "anullsrc=r=8000:cl=mono", "-shortest", "-c:a", "aac"]
    cmd += ["-c:v", "libx264", "-g", "60", "-bf", "2", "-crf", "12", "-pix_fmt", "yuv420p", str(path)]
    data = b"".join(frame_for(i + offset).tobytes() for i in range(n))
    subprocess.run(cmd, input=data, check=True, capture_output=True)


def template_text(fp: str, times, newline: str = "\n", a: str = "", minutes: str = "") -> str:
    """The exact lines glovescore.write_template (#31) writes."""
    lines = ["# format: glove-identity-labels-1", f"# video_fp: {fp}", "# every_s: 5", f"# A: {a}",
             f"# minutes: {minutes}",
             "# Fill A with the words that say who A is (e.g. 'the boxer in red gloves'); minutes = time spent.",
             "# a_side: L = A is on the left, R = A is on the right, ? = not clear. Every row needs one.",
             "t_s,a_side"] + [f"{t}," for t in times]
    return newline.join(lines) + newline


